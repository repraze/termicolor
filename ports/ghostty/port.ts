import {definePort} from "@termicolor/build";
import {type Ansi, flatten, type Mode} from "@termicolor/palette";

const ANSI_ORDER: (keyof Ansi)[] = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "brightBlack",
    "brightRed",
    "brightGreen",
    "brightYellow",
    "brightBlue",
    "brightMagenta",
    "brightCyan",
    "brightWhite",
];

function theme(mode: Mode): string {
    const {roles: r, accents: a, on, ansi} = mode;
    // Ghostty colors are opaque: flatten translucent roles over the background.
    const solid = (hex: string) => flatten(hex, r.bg);
    const entries: [string, string][] = [
        ...ANSI_ORDER.map((key, i): [string, string] => ["palette", `${i}=${ansi[key]}`]),
        ["background", r.bg],
        ["foreground", r.fg],
        ["cursor-color", r.cursor],
        ["cursor-text", r.onAccent],
        ["selection-background", solid(r.selection)],
        // keep each cell's own color inside the selection (Ghostty 1.2+)
        ["selection-foreground", "cell-foreground"],
        ["search-background", solid(r.findMatch)],
        ["search-foreground", r.fg],
        ["search-selected-background", a.orange],
        ["search-selected-foreground", on.orange],
        ["split-divider-color", r.borderStrong],
        // GTK only, used when window-theme = ghostty
        ["window-titlebar-background", r.bgSunken],
        ["window-titlebar-foreground", r.fg],
    ];
    return `# Termicolor ${mode.type === "dark" ? "Dark" : "Light"} - generated by https://github.com/repraze/termicolor

${entries.map(([k, v]) => `${k} = ${v}`).join("\n")}
`;
}

export default definePort({
    id: "ghostty",
    name: "Ghostty",
    category: "terminal",
    description: "Dark and light Ghostty themes: ANSI palette plus cursor, selection, search, splits and titlebar.",
    homepage: "https://ghostty.org",
    tags: ["gpu", "macos", "linux", "ansi"],
    install: `
Copy \`termicolor-dark\` and \`termicolor-light\` into \`~/.config/ghostty/themes/\`
(\`$XDG_CONFIG_HOME/ghostty/themes/\` if set), then in your Ghostty config:

\`\`\`ini
theme = light:termicolor-light,dark:termicolor-dark
\`\`\`

Or pin one with \`theme = termicolor-dark\`. Reload with *Reload Configuration* (\`cmd+shift+,\` / \`ctrl+shift+,\`).
The search colors apply to Ghostty's in-terminal search (1.3+); older versions warn about them and ignore them.
`,
    build: (palette) => [
        {path: "termicolor-dark", contents: theme(palette.modes.dark)},
        {path: "termicolor-light", contents: theme(palette.modes.light)},
    ],
});
