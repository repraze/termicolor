import {definePort} from "@termicolor/build";
import type {Ansi, Mode} from "@termicolor/palette";

const ANSI_ORDER: (keyof Ansi)[] = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "brightBlack",
    "brightRed",
    "brightGreen",
    "brightYellow",
    "brightBlue",
    "brightMagenta",
    "brightCyan",
    "brightWhite",
];

const title = (mode: Mode) => `Termicolor ${mode.type === "dark" ? "Dark" : "Light"}`;

function theme(mode: Mode): string {
    const {roles: r, fills, onFill, ansi} = mode;
    // kitty has no alpha in colors: use the `*Solid` roles.
    const sections: [string, [string, string][]][] = [
        [
            "Basic colors",
            [
                ["foreground", r.fg],
                ["background", r.bg],
                // keep each cell's own color inside the selection
                ["selection_foreground", "none"],
                ["selection_background", r.selectionSolid],
            ],
        ],
        [
            "Cursor",
            [
                ["cursor", r.cursor],
                ["cursor_text_color", r.onAccent],
            ],
        ],
        ["URL underline on hover", [["url_color", mode.syntax.link]]],
        [
            "Scrollbar",
            [
                ["scrollbar_handle_color", r.borderStrong],
                ["scrollbar_track_color", r.bgSunken],
            ],
        ],
        [
            "Window borders",
            [
                ["active_border_color", r.accent],
                ["inactive_border_color", r.borderStrong],
                ["bell_border_color", r.warning],
            ],
        ],
        [
            "Tab bar",
            [
                ["tab_bar_background", r.bgSunken],
                ["tab_bar_margin_color", r.bgSunken],
                ["active_tab_foreground", r.tabActiveFg],
                ["active_tab_background", r.tabActive],
                ["inactive_tab_foreground", r.tabInactiveFg],
                ["inactive_tab_background", r.tabInactive],
            ],
        ],
        [
            "Marks (search highlights)",
            [
                ["mark1_foreground", onFill.purple],
                ["mark1_background", fills.purple],
                ["mark2_foreground", onFill.blue],
                ["mark2_background", fills.blue],
                ["mark3_foreground", onFill.orange],
                ["mark3_background", fills.orange],
            ],
        ],
        ["The 16 terminal colors", ANSI_ORDER.map((key, i) => [`color${i}`, ansi[key]])],
    ];
    const body = sections
        .map(([heading, entries]) => [`# ${heading}`, ...entries.map(([k, v]) => `${k.padEnd(24)}${v}`)].join("\n"))
        .join("\n\n");
    return `# vim:ft=kitty

## name: ${title(mode)}
## author: repraze
## license: MIT
## upstream: https://github.com/repraze/termicolor
## blurb: High contrast, bright, techy colors. Generated by termicolor - do not edit.

${body}
`;
}

export default definePort({
    id: "kitty",
    name: "kitty",
    category: "terminal",
    description: "Dark and light kitty themes: ANSI colors plus cursor, selection, borders, tab bar and marks.",
    homepage: "https://sw.kovidgoyal.net/kitty/",
    tags: ["gpu", "linux", "macos", "ansi"],
    install: `
**Theme kitten:** copy \`termicolor-dark.conf\` and \`termicolor-light.conf\` into \`~/.config/kitty/themes/\`,
then run \`kitten themes\` and pick *Termicolor Dark* (it's listed under *user-defined*), or apply it directly:

\`\`\`sh
kitten themes "Termicolor Dark"
\`\`\`

**Follow the OS light/dark setting:** copy the files into the kitty config folder as
\`dark-theme.auto.conf\` and \`light-theme.auto.conf\` (on GNOME also copy the light one as
\`no-preference-theme.auto.conf\`), then restart kitty.

**Manual:** add \`include termicolor-dark.conf\` to \`~/.config/kitty/kitty.conf\`.
`,
    build: (palette) => [
        {path: "termicolor-dark.conf", contents: theme(palette.modes.dark)},
        {path: "termicolor-light.conf", contents: theme(palette.modes.light)},
    ],
});
