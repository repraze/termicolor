import {definePort} from "@termicolor/build";
import {type Mode, solid} from "@termicolor/palette";

type Table = [string, [string, string][]];

const ANSI_NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const;

const bright = (name: (typeof ANSI_NAMES)[number]) =>
    `bright${name.charAt(0).toUpperCase()}${name.slice(1)}` as `bright${Capitalize<typeof name>}`;

function theme(mode: Mode): string {
    const {roles: r, accents: a, on, fills, onFill, ansi, ansiDim} = mode;
    // Alacritty colors are opaque `#rrggbb`: translucent roles go through `solid()`.
    const dim = ansiDim;
    const tables: Table[] = [
        [
            "colors.primary",
            [
                ["background", r.bg],
                ["foreground", r.fg],
                ["dim_foreground", r.fgSoft],
            ],
        ],
        [
            "colors.cursor",
            [
                ["text", r.onAccent],
                ["cursor", r.cursor],
            ],
        ],
        [
            "colors.vi_mode_cursor",
            [
                ["text", on.cyan],
                ["cursor", a.cyan],
            ],
        ],
        [
            "colors.search.matches",
            [
                ["foreground", r.fg],
                ["background", solid(r.findMatch, r.bg)],
            ],
        ],
        [
            "colors.search.focused_match",
            [
                ["foreground", r.onMatchActive],
                ["background", r.matchActive],
            ],
        ],
        [
            "colors.footer_bar",
            [
                ["foreground", r.fg],
                ["background", r.bgRaised],
            ],
        ],
        [
            "colors.hints.start",
            [
                ["foreground", onFill.yellow],
                ["background", fills.yellow],
            ],
        ],
        [
            "colors.hints.end",
            [
                ["foreground", r.fg],
                ["background", r.bgRaised],
            ],
        ],
        [
            "colors.line_indicator",
            [
                ["foreground", r.fgSoft],
                ["background", r.bgRaised],
            ],
        ],
        [
            "colors.selection",
            [
                // keep each cell's own color inside the selection
                ["text", "CellForeground"],
                ["background", solid(r.selection, r.bg)],
            ],
        ],
        ["colors.normal", ANSI_NAMES.map((name) => [name, ansi[name]])],
        ["colors.bright", ANSI_NAMES.map((name) => [name, ansi[bright(name)]])],
        ["colors.dim", ANSI_NAMES.map((name) => [name, dim[name]])],
    ];
    const body = tables
        .map(([name, entries]) => [`[${name}]`, ...entries.map(([k, v]) => `${k} = "${v}"`)].join("\n"))
        .join("\n\n");
    return `# Termicolor ${mode.type === "dark" ? "Dark" : "Light"} - generated by https://github.com/repraze/termicolor

${body}
`;
}

export default definePort({
    id: "alacritty",
    name: "Alacritty",
    category: "terminal",
    description:
        "Dark and light Alacritty color files: ANSI colors (normal, bright and dim) plus cursor, vi-mode, selection, search, hints and footer bar.",
    homepage: "https://alacritty.org",
    tags: ["gpu", "toml", "ansi"],
    install: `
Copy \`termicolor-dark.toml\` (or \`-light\`) next to your config, e.g. \`~/.config/alacritty/\`
(\`%APPDATA%\\alacritty\\\` on Windows), and import it from \`alacritty.toml\`:

\`\`\`toml
[general]
import = ["~/.config/alacritty/termicolor-dark.toml"]
\`\`\`

Alacritty reloads the config live.
Needs Alacritty 0.13+ (TOML config).
`,
    build: (palette) => [
        {path: "termicolor-dark.toml", contents: theme(palette.modes.dark)},
        {path: "termicolor-light.toml", contents: theme(palette.modes.light)},
    ],
});
