import type {Mode} from "@repraze/termicolor";
import {definePort, json} from "@termicolor/build";

import pkg from "../../package.json" with {type: "json"};
import {scheme} from "./scheme.ts";
import {uiTheme} from "./ui-theme.ts";

const slug = (mode: Mode) => `termicolor-${mode.type}`;

const PLUGIN_XML = `<idea-plugin>
    <id>com.repraze.termicolor</id>
    <name>Termicolor</name>
    <version>${pkg.version}</version>
    <vendor url="https://github.com/repraze/termicolor">repraze</vendor>
    <description>High contrast, bright, techy dark and light UI themes with matching editor color schemes. Generated by termicolor.</description>
    <idea-version since-build="223"/>
    <depends>com.intellij.modules.platform</depends>
    <extensions defaultExtensionNs="com.intellij">
        <themeProvider id="com.repraze.termicolor.dark" path="/themes/termicolor-dark.theme.json"/>
        <themeProvider id="com.repraze.termicolor.light" path="/themes/termicolor-light.theme.json"/>
    </extensions>
</idea-plugin>
`;

export default definePort({
    id: "jetbrains",
    name: "JetBrains IDEs",
    category: "editor",
    description:
        "Editor color schemes and UI themes for IntelliJ IDEA, WebStorm, PyCharm and the other JetBrains IDEs.",
    homepage: "https://www.jetbrains.com",
    tags: ["intellij", "webstorm", "pycharm", "goland", "rider", "clion", "phpstorm", "rubymine", "android studio"],
    install: `
**Editor color scheme (no plugin needed):** *Settings → Editor → Color Scheme*, click the gear next to
the scheme list, *Import Scheme…*, and pick \`termicolor-dark.icls\` or \`termicolor-light.icls\`.
This colors the editor, console, diff and gutter; the rest of the IDE keeps its current theme.

**Full UI theme:** IDE themes only load from a plugin. A theme plugin is just a jar (a zip) holding
\`META-INF/plugin.xml\` and the theme files, so build it from the \`plugin\` folder:

\`\`\`sh
cd ports/jetbrains/dist/plugin
zip -r ../termicolor-jetbrains.jar META-INF themes
\`\`\`

(Or, with a JDK, \`jar cf ../termicolor-jetbrains.jar META-INF themes\`.)

Then *Settings → Plugins*, gear, *Install Plugin from Disk…*, pick \`termicolor-jetbrains.jar\` and
restart. Choose **Termicolor Dark** or **Termicolor Light** in *Settings → Appearance & Behavior →
Appearance → Theme*; each theme switches the editor to its matching scheme.
`,
    build: (palette) => {
        const modes = [palette.modes.dark, palette.modes.light];
        return [
            ...modes.map((mode) => ({path: `${slug(mode)}.icls`, contents: scheme(mode)})),
            {path: "plugin/META-INF/plugin.xml", contents: PLUGIN_XML},
            ...modes.flatMap((mode) => [
                {path: `plugin/themes/${slug(mode)}.xml`, contents: scheme(mode)},
                {
                    path: `plugin/themes/${slug(mode)}.theme.json`,
                    contents: json(uiTheme(mode, `/themes/${slug(mode)}.xml`)),
                },
            ]),
        ];
    },
});
