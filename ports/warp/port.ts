import type {Ansi, Mode} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

const NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const;

function group(ansi: Ansi, bright: boolean): string {
    return NAMES.map((name) => {
        const key = bright ? (`bright${name.charAt(0).toUpperCase()}${name.slice(1)}` as keyof Ansi) : name;
        return `    ${name}: '${ansi[key]}'`;
    }).join("\n");
}

function theme({type, roles: r, ansi}: Mode): string {
    return `# Termicolor ${type} - generated by https://github.com/repraze/termicolor
name: Termicolor ${type === "dark" ? "Dark" : "Light"}
accent: '${r.accent}'
cursor: '${r.cursor}'
background: '${r.bg}'
foreground: '${r.fg}'
details: ${type === "dark" ? "darker" : "lighter"}
terminal_colors:
  normal:
${group(ansi, false)}
  bright:
${group(ansi, true)}
`;
}

export default definePort({
    id: "warp",
    name: "Warp",
    category: "terminal",
    description: "Dark and light custom themes for the Warp terminal.",
    homepage: "https://www.warp.dev",
    tags: ["ansi", "yaml", "macos", "linux", "windows"],
    install: `
1. Copy \`termicolor_dark.yaml\` and \`termicolor_light.yaml\` into Warp's themes folder (create it if missing):
    - macOS: \`~/.warp/themes/\`
    - Linux: \`\${XDG_DATA_HOME:-$HOME/.local/share}/warp-terminal/themes/\`
    - Windows: \`%APPDATA%\\warp\\Warp\\data\\themes\\\`
2. Restart Warp, then pick **Termicolor Dark** or **Termicolor Light** in *Settings → Appearance → Themes*.

To follow the OS, enable *Sync with OS* there and assign one theme to each mode.
`,
    build: (palette) => [
        {path: "termicolor_dark.yaml", contents: theme(palette.modes.dark)},
        {path: "termicolor_light.yaml", contents: theme(palette.modes.light)},
    ],
});
