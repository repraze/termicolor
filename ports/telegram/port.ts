const title = (mode: Mode) => `Termicolor ${mode.type === "dark" ? "Dark" : "Light"}`;

function file(mode: Mode, modes: Palette["modes"]): string {
    const body = sections(mode, modes)
        .map(([heading, entries]) => [`// ${heading}`, ...entries.map(([k, v]) => `${k}: ${v};`)].join("\n"))
        .join("\n\n");
    return `// ${title(mode)} - Telegram Desktop color palette
// High contrast, bright, techy colors. Generated by https://github.com/repraze/termicolor - do not edit.
// License: MIT

${body}
`;
}

