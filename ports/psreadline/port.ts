import {definePort} from "@termicolor/build";
import {flatten, type Hex, type Mode, rgb} from "@termicolor/palette";

/** 24-bit SGR body, e.g. `38;2;255;76;130`. */
function sgr(hex: Hex, layer: "fg" | "bg" = "fg"): string {
    const {r, g, b} = rgb(hex);
    return `${layer === "fg" ? 38 : 48};2;${r};${g};${b}`;
}

/** A PowerShell string holding an escape sequence; `$e` is `[char]27` (works in Windows PowerShell 5.1 too). */
const esc = (...parts: string[]) => `"\${e}[${parts.join(";")}m"`;

type Entry = [key: string, value: string];

function script(mode: Mode): string {
    const {roles: r, syntax: s, accents: a} = mode;
    const base: Entry[] = [
        ["Default", esc(sgr(r.fg))],
        ["Comment", esc(sgr(s.comment))],
        ["Keyword", esc(sgr(s.keyword))],
        ["String", esc(sgr(s.string))],
        ["Operator", esc(sgr(s.operator))],
        // PowerShell `$variables` read better with their own hue; syntax.variable is plain fg.
        ["Variable", esc(sgr(a.pink))],
        ["Command", esc(sgr(s.function))],
        ["Parameter", esc(sgr(a.cyan))],
        ["Type", esc(sgr(s.type))],
        ["Number", esc(sgr(s.number))],
        ["Member", esc(sgr(s.property))],
        ["Emphasis", esc(sgr(r.accent), "1")],
        ["Error", esc(sgr(r.danger))],
        ["ContinuationPrompt", esc(sgr(r.fgMuted))],
        ["Selection", esc(sgr(r.fg), sgr(flatten(r.selection, r.bg), "bg"))],
    ];
    const v21: Entry[] = [["InlinePrediction", esc(sgr(r.fgMuted))]];
    const v22: Entry[] = [
        ["ListPrediction", esc(sgr(r.accent))],
        ["ListPredictionSelected", esc(sgr(r.bgRaised, "bg"))],
    ];
    const lines = (entries: Entry[]) => entries.map(([k, v]) => `        ${k.padEnd(18)} = ${v}`).join("\n");
    const adds = (entries: Entry[]) => entries.map(([k, v]) => `        $colors.${k} = ${v}`).join("\n");
    return `# Termicolor ${mode.type} for PSReadLine - generated by https://github.com/repraze/termicolor
# Dot-source this file from your PowerShell profile:  . "$HOME\\termicolor-${mode.name}.ps1"
# Uses 24-bit color escapes; needs a truecolor terminal (Windows Terminal, VS Code, most modern terminals).

& {
    $e = [char]27
    $colors = @{
${lines(base)}
    }

    $psrl = (Get-Module PSReadLine).Version
    if ($psrl -ge [version]"2.1.0") {
${adds(v21)}
    }
    if ($psrl -ge [version]"2.2.0") {
${adds(v22)}
    }

    Set-PSReadLineOption -Colors $colors
}
`;
}

export default definePort({
    id: "psreadline",
    name: "PowerShell PSReadLine",
    category: "shell",
    description: "Command-line syntax colors for PowerShell (PSReadLine), in dark and light.",
    homepage: "https://github.com/PowerShell/PSReadLine",
    tags: ["powershell", "pwsh", "windows", "syntax"],
    install: `
1. Save \`termicolor-dark.ps1\` (or \`-light\`) somewhere, for example next to your profile.
2. Open your profile (\`notepad $PROFILE\`, or \`code $PROFILE\`) and dot-source it:

    \`\`\`powershell
    . "$HOME\\Documents\\PowerShell\\termicolor-dark.ps1"
    \`\`\`

3. Restart the shell.

Prediction colors are only set where your PSReadLine supports them (2.1+ inline, 2.2+ list view).
Windows PowerShell 5.1 ships PSReadLine 2.0; \`Install-Module PSReadLine -Force\` gets the current one.
Pair it with a Termicolor terminal scheme (e.g. Windows Terminal) for matching ANSI colors.
`,
    build: (palette) => [
        {path: "termicolor-dark.ps1", contents: script(palette.modes.dark)},
        {path: "termicolor-light.ps1", contents: script(palette.modes.light)},
    ],
});
