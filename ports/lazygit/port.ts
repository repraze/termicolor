import {definePort} from "@termicolor/build";
import type {Hex, Mode} from "@termicolor/palette";

const HEADER = "# Termicolor for lazygit - generated by https://github.com/repraze/termicolor";

/** `gui.theme` fields. Each value is a lazygit attribute list: at most one color plus modifiers. */
function theme({roles: r, accents: a, fills, onFill}: Mode): Record<string, (Hex | string)[]> {
    return {
        activeBorderColor: [r.accent, "bold"],
        inactiveBorderColor: [r.fgMuted],
        searchingActiveBorderColor: [a.orange, "bold"],
        optionsTextColor: [a.blue],
        selectedLineFgColor: ["bold"],
        selectedLineBgColor: [r.selectionSolid],
        inactiveViewSelectedLineBgColor: [r.selectionInactiveSolid],
        cherryPickedCommitFgColor: [onFill.cyan],
        cherryPickedCommitBgColor: [fills.cyan],
        markedBaseCommitFgColor: [onFill.yellow],
        markedBaseCommitBgColor: [fills.yellow],
        unstagedChangesColor: [r.removed],
        defaultFgColor: [r.fg],
    };
}

function block(mode: Mode, indent: string): string {
    return Object.entries(theme(mode))
        .map(([key, values]) => `${indent}${key}:\n${values.map((v) => `${indent}  - "${v}"`).join("\n")}`)
        .join("\n");
}

export default definePort({
    id: "lazygit",
    name: "lazygit",
    category: "cli",
    description: "Git TUI theme: borders, selection, cherry-pick and rebase markers.",
    homepage: "https://github.com/jesseduffield/lazygit",
    tags: ["git", "tui"],
    install: `
Merge one of the files into your lazygit \`config.yml\`:

| OS      | Path                                              |
| ------- | ------------------------------------------------- |
| Linux   | \`~/.config/lazygit/config.yml\`                  |
| macOS   | \`~/Library/Application Support/lazygit/config.yml\` |
| Windows | \`%LOCALAPPDATA%\\lazygit\\config.yml\`             |

- \`lazygit-dark.yml\` / \`lazygit-light.yml\` set \`gui.theme\` for one mode.
- \`lazygit-auto.yml\` sets \`gui.darkTheme\` and \`gui.lightTheme\`, and lazygit picks one from the terminal's
  background (\`gui.colorScheme: auto\`). Needs a lazygit recent enough to have those keys.

To keep the theme in its own file, layer it over your config instead of copying it in:

\`\`\`sh
export LG_CONFIG_FILE="$HOME/.config/lazygit/config.yml,$HOME/.config/lazygit/lazygit-dark.yml"
\`\`\`
`,
    build: (palette) => {
        const {dark, light} = palette.modes;
        return [
            {path: "lazygit-dark.yml", contents: `${HEADER}\ngui:\n  theme:\n${block(dark, "    ")}\n`},
            {path: "lazygit-light.yml", contents: `${HEADER}\ngui:\n  theme:\n${block(light, "    ")}\n`},
            {
                path: "lazygit-auto.yml",
                contents: `${HEADER}\ngui:\n  colorScheme: auto\n  darkTheme:\n${block(dark, "    ")}\n  lightTheme:\n${block(light, "    ")}\n`,
            },
        ];
    },
});
