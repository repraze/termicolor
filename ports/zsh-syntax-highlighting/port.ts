import {definePort} from "@termicolor/build";
import type {Mode} from "@termicolor/palette";

/**
 * Styles for the main, brackets and cursor highlighters. Values use zle_highlight syntax: zsh 5.7+
 * understands `fg=#rrggbb` (24-bit, or nearest 256 color with `zmodload zsh/nearcolor`). zle has
 * no italic, so comments are only dimmed by color.
 */
function styles({roles: r, syntax: s}: Mode): [string, string][] {
    const fg = (hex: string, ...attrs: string[]) => [`fg=${hex}`, ...attrs].join(",");
    return [
        // main highlighter
        ["default", "none"],
        ["unknown-token", fg(r.danger, "bold")],
        ["reserved-word", fg(s.keyword)],
        ["alias", fg(s.builtin)],
        ["suffix-alias", fg(s.builtin, "underline")],
        ["global-alias", fg(s.builtin)],
        ["builtin", fg(s.builtin)],
        ["function", fg(s.function)],
        ["command", fg(s.function)],
        ["precommand", fg(s.keyword, "underline")],
        ["hashed-command", fg(s.function)],
        ["arg0", fg(s.function)],
        ["autodirectory", fg(s.function, "underline")],
        ["commandseparator", fg(s.keyword)],
        ["redirection", fg(s.keyword)],
        ["named-fd", fg(s.number)],
        ["numeric-fd", fg(s.number)],
        ["path", fg(r.fg, "underline")],
        ["path_pathseparator", fg(r.fgSoft, "underline")],
        ["path_prefix", fg(r.fg, "underline")],
        ["path_prefix_pathseparator", fg(r.fgSoft, "underline")],
        ["globbing", fg(s.regexp)],
        ["history-expansion", fg(s.regexp)],
        ["single-hyphen-option", fg(s.builtin)],
        ["double-hyphen-option", fg(s.builtin)],
        // shell variables get their own hue so they don't vanish among commands
        ["assign", fg(s.parameter)],
        ["arithmetic-expansion", fg(s.number)],
        ["command-substitution", "none"],
        ["command-substitution-unquoted", "none"],
        ["command-substitution-quoted", fg(s.string)],
        ["command-substitution-delimiter", fg(s.punctuation)],
        ["command-substitution-delimiter-unquoted", fg(s.punctuation)],
        ["command-substitution-delimiter-quoted", fg(s.punctuation)],
        ["process-substitution", "none"],
        ["process-substitution-delimiter", fg(s.punctuation)],
        ["back-quoted-argument", "none"],
        ["back-quoted-argument-delimiter", fg(s.punctuation)],
        ["back-quoted-argument-unclosed", fg(r.danger)],
        ["single-quoted-argument", fg(s.string)],
        ["single-quoted-argument-unclosed", fg(r.danger)],
        ["double-quoted-argument", fg(s.string)],
        ["double-quoted-argument-unclosed", fg(r.danger)],
        ["dollar-quoted-argument", fg(s.string)],
        ["dollar-quoted-argument-unclosed", fg(r.danger)],
        ["rc-quote", fg(s.escape)],
        ["dollar-double-quoted-argument", fg(s.parameter)],
        ["back-double-quoted-argument", fg(s.escape)],
        ["back-dollar-quoted-argument", fg(s.escape)],
        ["comment", fg(s.comment)],
        // brackets highlighter: same order as the VS Code bracket pair colors
        ["bracket-error", fg(r.danger, "bold")],
        ["bracket-level-1", fg(s.bracket1)],
        ["bracket-level-2", fg(s.bracket2)],
        ["bracket-level-3", fg(s.bracket3)],
        ["bracket-level-4", fg(s.bracket4)],
        ["bracket-level-5", fg(s.bracket5)],
        ["bracket-level-6", fg(s.bracket6)],
        ["cursor-matchingbracket", "standout"],
    ];
}

function file(mode: Mode): string {
    const lines = styles(mode).map(([key, value]) => `ZSH_HIGHLIGHT_STYLES[${key}]='${value}'`);
    return `# Termicolor ${mode.name} for zsh-syntax-highlighting - generated by https://github.com/repraze/termicolor
# Source this before zsh-syntax-highlighting.zsh. Needs zsh 5.7+ for hex colors.

typeset -gA ZSH_HIGHLIGHT_STYLES

${lines.join("\n")}
`;
}

export default definePort({
    id: "zsh-syntax-highlighting",
    name: "zsh-syntax-highlighting",
    category: "shell",
    description: "Fish-like command line highlighting for zsh, in the same syntax colors as the editor themes.",
    homepage: "https://github.com/zsh-users/zsh-syntax-highlighting",
    tags: ["zsh", "shell"],
    install: `
Copy \`termicolor-dark.zsh\` (or \`-light\`) to \`~/.config/zsh/\` and source it in \`~/.zshrc\`, before the plugin
(which must stay the last thing sourced):

\`\`\`zsh
source ~/.config/zsh/termicolor-dark.zsh
ZSH_HIGHLIGHT_HIGHLIGHTERS=(main brackets)   # optional: colored bracket levels
source /path/to/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh
\`\`\`

With a plugin manager, load the theme file before the plugin (oh-my-zsh: source it above \`source $ZSH/oh-my-zsh.sh\`).

Colors are 24-bit hex, which needs zsh 5.7+ and a truecolor terminal. On a 256-color terminal, add
\`zmodload zsh/nearcolor\` before sourcing the theme.
`,
    build: (palette) => [
        {path: "termicolor-dark.zsh", contents: file(palette.modes.dark)},
        {path: "termicolor-light.zsh", contents: file(palette.modes.light)},
    ],
});
