import {definePort, type PortFile} from "@termicolor/build";
import type {Mode} from "@termicolor/palette";

const HEADER = "Termicolor for fzf - generated by https://github.com/repraze/termicolor";

/** `--color` groups, one per line. fzf merges repeated `--color` options. */
function colorOptions(mode: Mode): string[] {
    const {roles: r, accents: a} = mode;
    const groups: Record<string, string>[] = [
        {fg: r.fg, bg: r.bg, hl: r.accent},
        {"fg+": r.fg, "bg+": r.bgRaised, "hl+": r.accent, gutter: r.bg},
        {"selected-fg": r.fg, "selected-bg": r.selectionInactiveSolid},
        {query: r.fg, ghost: r.fgMuted, disabled: r.fgDisabled, prompt: r.accent, info: r.fgSoft},
        {pointer: r.accent, marker: a.green, spinner: r.accent, header: a.blue, footer: a.blue},
        {border: r.borderStrong, separator: r.border, scrollbar: r.borderStrong, label: r.fgSoft},
    ];
    const lines = groups.map((group) =>
        Object.entries(group)
            .map(([name, color]) => `${name}:${color}`)
            .join(","),
    );
    return lines.map((line, i) => `--color=${i === 0 ? `${mode.type},` : ""}${line}`);
}

function files(mode: Mode): PortFile[] {
    const options = colorOptions(mode);
    const name = `fzf-${mode.name}`;
    return [
        {
            // for FZF_DEFAULT_OPTS_FILE (fzf 0.48+): one option per line, no quoting
            path: `${name}.opts`,
            contents: `${options.join("\n")}\n`,
        },
        {
            path: `${name}.sh`,
            contents: `# ${HEADER}\n# bash / zsh: source this file from ~/.bashrc or ~/.zshrc\nexport FZF_DEFAULT_OPTS="$FZF_DEFAULT_OPTS \\\n  ${options.join(" \\\n  ")}"\n`,
        },
        {
            path: `${name}.fish`,
            contents: `# ${HEADER}\n# fish: source this file from ~/.config/fish/config.fish\nset -gx FZF_DEFAULT_OPTS (string join ' ' -- $FZF_DEFAULT_OPTS \\\n${options.map((o) => `    '${o}'`).join(" \\\n")})\n`,
        },
        {
            path: `${name}.ps1`,
            contents: `# ${HEADER}\n# PowerShell: dot-source this file from your $PROFILE\n$env:FZF_DEFAULT_OPTS = @(\n    $env:FZF_DEFAULT_OPTS\n${options.map((o) => `    '${o}'`).join("\n")}\n) -join ' '\n`,
        },
    ];
}

export default definePort({
    id: "fzf",
    name: "fzf",
    category: "cli",
    description: "Fuzzy finder colors as FZF_DEFAULT_OPTS snippets for bash, zsh, fish and PowerShell.",
    homepage: "https://github.com/junegunn/fzf",
    tags: ["fuzzy", "bash", "zsh", "fish", "powershell"],
    install: `
Copy the files you need to \`~/.config/fzf/\` (any folder works, adjust the paths below).
Each snippet appends \`--color\` options to \`FZF_DEFAULT_OPTS\`, so load it after anything else that sets it.
Use the \`-light\` files on a light terminal.

**bash / zsh:** add to \`~/.bashrc\` or \`~/.zshrc\`:

\`\`\`sh
source ~/.config/fzf/fzf-dark.sh
\`\`\`

**fish:** add to \`~/.config/fish/config.fish\`:

\`\`\`fish
source ~/.config/fzf/fzf-dark.fish
\`\`\`

**PowerShell:** add to \`$PROFILE\`:

\`\`\`powershell
. "$HOME\\.config\\fzf\\fzf-dark.ps1"
\`\`\`

**Any shell (fzf 0.48+):** point \`FZF_DEFAULT_OPTS_FILE\` at \`fzf-dark.opts\`, which holds the bare options:

\`\`\`sh
export FZF_DEFAULT_OPTS_FILE=~/.config/fzf/fzf-dark.opts
\`\`\`

Newer color names (\`ghost\`, \`footer\`) need a recent fzf. Older releases reject names they don't know,
so upgrade fzf or delete those entries.
`,
    build: (palette) => [...files(palette.modes.dark), ...files(palette.modes.light)],
});
