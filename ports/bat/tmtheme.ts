import {flatten, type Hex} from "@termicolor/palette";

/** A VS Code / TextMate token rule, as `ports/vscode/token-colors.ts` produces them. */
export type TokenRule = {
    name?: string;
    scope: string | string[];
    settings: {foreground?: Hex; background?: Hex; fontStyle?: string};
};

/** syntect (bat, delta) rejects any font style other than these. */
const FONT_STYLES = new Set(["bold", "italic", "underline"]);

function escape(text: string): string {
    return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function dict(entries: Record<string, string>, indent: string): string {
    const lines = Object.entries(entries).map(
        ([key, value]) => `${indent}\t<key>${escape(key)}</key>\n${indent}\t<string>${escape(value)}</string>`,
    );
    return `${indent}<dict>\n${lines.join("\n")}\n${indent}</dict>`;
}

export type TmThemeOptions = {
    name: string;
    uuid: string;
    /** Global settings: background, foreground, caret, selection, lineHighlight, gutterForeground, ... */
    globals: Record<string, Hex> & {background: Hex};
    rules: TokenRule[];
};

/**
 * Renders a TextMate `.tmTheme` plist. Translucent colors are flattened over the theme background
 * (syntect handles `#rrggbbaa` inconsistently), and font styles syntect can't parse, such as
 * `strikethrough`, are dropped.
 */
export function tmTheme({name, uuid, globals, rules}: TmThemeOptions): string {
    const color = (hex: Hex) => flatten(hex, globals.background);
    const globalSettings = Object.fromEntries(Object.entries(globals).map(([k, v]) => [k, color(v)]));

    const items = [`\t\t<dict>\n\t\t\t<key>settings</key>\n${dict(globalSettings, "\t\t\t")}\n\t\t</dict>`];
    for (const rule of rules) {
        const settings: Record<string, string> = {};
        if (rule.settings.foreground) {
            settings.foreground = color(rule.settings.foreground);
        }
        if (rule.settings.background) {
            settings.background = color(rule.settings.background);
        }
        if (rule.settings.fontStyle !== undefined) {
            const styles = rule.settings.fontStyle.split(/\s+/).filter((s) => FONT_STYLES.has(s));
            if (styles.length) {
                settings.fontStyle = styles.join(" ");
            }
        }
        if (!Object.keys(settings).length) {
            continue;
        }
        const scopes = Array.isArray(rule.scope) ? rule.scope : [rule.scope];
        items.push(
            [
                "\t\t<dict>",
                `\t\t\t<key>name</key>\n\t\t\t<string>${escape(rule.name ?? scopes[0] ?? "")}</string>`,
                `\t\t\t<key>scope</key>\n\t\t\t<string>${escape(scopes.join(", "))}</string>`,
                `\t\t\t<key>settings</key>\n${dict(settings, "\t\t\t")}`,
                "\t\t</dict>",
            ].join("\n"),
        );
    }

    return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by https://github.com/repraze/termicolor - do not edit -->
<plist version="1.0">
<dict>
\t<key>name</key>
\t<string>${escape(name)}</string>
\t<key>uuid</key>
\t<string>${uuid}</string>
\t<key>colorSpaceName</key>
\t<string>sRGB</string>
\t<key>settings</key>
\t<array>
${items.join("\n")}
\t</array>
</dict>
</plist>
`;
}
