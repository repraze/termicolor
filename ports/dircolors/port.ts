import {type Hex, type Mode, rgb} from "@termicolor/palette";

type Style = {fg?: Hex; bg?: Hex; bold?: boolean; underline?: boolean; dim?: boolean};

/** 24-bit SGR, e.g. `38;2;77;145;255;1`. */
function sgr({fg, bg, bold, underline, dim}: Style): string {
    const parts: (string | number)[] = [];
    const color = (layer: number, hex: Hex) => {
        const {r, g, b} = rgb(hex);
        parts.push(layer, 2, r, g, b);
    };
    if (fg) {
        color(38, fg);
    }
    if (bg) {
        color(48, bg);
    }
    if (bold) {
        parts.push(1);
    }
    if (dim) {
        parts.push(2);
    }
    if (underline) {
        parts.push(4);
    }
    return parts.length ? parts.join(";") : "0";
}

