function shell(mode: Mode, kind: "sh" | "fish"): string {
    const head = `# Termicolor ${mode.type} LS_COLORS - generated by https://github.com/repraze/termicolor\n`;
    const value = lsColors(mode);
    return kind === "sh" ? `${head}export LS_COLORS='${value}'\n` : `${head}set -gx LS_COLORS '${value}'\n`;
}

export default definePort({
    id: "dircolors",
    name: "LS_COLORS",
    category: "shell",
    description:
        "Truecolor LS_COLORS for ls, eza, fd, tree and other tools that read it, plus an eza theme.yml for permissions, sizes and git columns.",
    homepage: "https://www.gnu.org/software/coreutils/manual/html_node/dircolors-invocation.html",
    tags: ["eza", "dircolors", "ls", "fd", "tree", "lscolors", "bash", "zsh", "fish"],
    install: `
**dircolors (bash/zsh):** save \`termicolor-dark.dircolors\` (or \`-light\`) as \`~/.dircolors\` and add to your rc file:

\`\`\`sh
eval "$(dircolors -b ~/.dircolors)"
\`\`\`

**No dircolors** (macOS without coreutils, fish, or just simpler): source the prebuilt string instead,
\`ls-colors-dark.sh\` from bash/zsh or \`ls-colors-dark.fish\` from \`config.fish\`. GNU \`ls\` needs
\`--color=auto\`; BSD/macOS \`ls\` ignores \`LS_COLORS\`, but eza, fd, lsd and tree read it.

**eza:** copy \`eza-dark.yml\` (or \`-light\`) to \`~/.config/eza/theme.yml\` (or \`$EZA_CONFIG_DIR/theme.yml\`).
It colors permissions, sizes, users, dates and git status. \`LS_COLORS\` / \`EZA_COLORS\` win where they
overlap, so keep the two in the same mode.

All colors are 24-bit; use a truecolor terminal.
`,
    build: (palette) =>
        [palette.modes.dark, palette.modes.light].flatMap((mode) => [
            {path: `termicolor-${mode.name}.dircolors`, contents: dircolors(mode)},
            {path: `ls-colors-${mode.name}.sh`, contents: shell(mode, "sh")},
            {path: `ls-colors-${mode.name}.fish`, contents: shell(mode, "fish")},
            {path: `eza-${mode.name}.yml`, contents: ezaTheme(mode)},
        ]),
});
