import {type Hex, type Mode, solid} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

const HEADER = "# Termicolor for tmux - generated by https://github.com/repraze/termicolor";

/** A tmux style string. Inside a `#{?...}` conditional its commas must be escaped as `#,`. */
const style = (...attrs: string[]) => attrs.join(",");
const inline = (...attrs: string[]) => `#[${attrs.join("#,")}]`;
/** Single quotes: tmux expands nothing inside them. */
const quote = (value: string) => `'${value}'`;

function options(mode: Mode): [string, [string, string][]][] {
    const {roles: r, fills, onFill} = mode;
    const fg = (c: Hex) => `fg=${c}`;
    const bg = (c: Hex) => `bg=${c}`;
    const selection = solid(r.selection, r.bg);
    const match = solid(r.findMatch, r.bg);

    // the session segment turns yellow while the prefix key is held
    const session =
        `#{?client_prefix,${inline(bg(fills.yellow), fg(onFill.yellow))},${inline(bg(r.accentFill), fg(r.onAccentFill))}}` +
        "#[bold] #S #[default] ";
    const clock = `#[${style(fg(r.fgSoft))}]%Y-%m-%d #[${style(fg(r.fg), "bold")}]%H:%M #[${style(bg(r.bgRaised), fg(r.fg), "nobold")}] #h `;
    const zoom = `#{?window_zoomed_flag,${inline(fg(r.warning))} +,}`;

    return [
        [
            "Status bar",
            [
                ["status-style", style(bg(r.bgSunken), fg(r.fgSoft))],
                ["status-left-length", "40"],
                ["status-right-length", "60"],
                ["status-left", session],
                ["status-right", clock],
            ],
        ],
        [
            "Windows: the current one is an accent index next to fg text, others are soft",
            [
                ["window-status-separator", ""],
                ["window-status-style", style(bg(r.tabInactive), fg(r.tabInactiveFg))],
                ["window-status-format", ` #I #W${zoom} `],
                ["window-status-current-style", style(bg(r.tabActive), fg(r.tabActiveFg))],
                [
                    "window-status-current-format",
                    ` #[${style(fg(r.accent), "bold")}]#I #[${style(fg(r.tabActiveFg), "bold")}]#W${zoom} `,
                ],
                ["window-status-activity-style", style("none", bg(r.tabInactive), fg(r.warning))],
                ["window-status-bell-style", style(bg(r.tabInactive), fg(r.danger), "bold")],
            ],
        ],
        [
            "Pane borders",
            [
                ["pane-border-style", fg(r.border)],
                ["pane-active-border-style", fg(r.accent)],
                ["display-panes-colour", r.fgMuted],
                ["display-panes-active-colour", r.accent],
            ],
        ],
        [
            "Messages and the command prompt",
            [
                ["message-style", style(bg(r.bgRaised), fg(r.fg))],
                ["message-command-style", style(bg(r.bgRaised), fg(r.accent))],
            ],
        ],
        [
            "Copy mode: selection, search matches (copy-mode-*-style needs tmux 3.4+), marks",
            [
                ["mode-style", style(bg(selection), fg(r.fg))],
                ["copy-mode-match-style", style(bg(match), fg(r.fg))],
                ["copy-mode-current-match-style", style(bg(r.matchActive), fg(r.onMatchActive))],
                ["copy-mode-mark-style", style(bg(fills.cyan), fg(onFill.cyan))],
                ["clock-mode-colour", r.accent],
            ],
        ],
        [
            "Popups and menus",
            [
                ["popup-style", style(bg(r.bgRaised), fg(r.fg))],
                ["popup-border-style", fg(r.borderStrong)],
                ["menu-style", style(bg(r.bgRaised), fg(r.fg))],
                ["menu-selected-style", style(bg(r.accentFill), fg(r.onAccentFill))],
                ["menu-border-style", fg(r.borderStrong)],
            ],
        ],
    ];
}

function theme(mode: Mode): string {
    const body = options(mode)
        .map(([heading, entries]) => [`# ${heading}`, ...entries.map(([k, v]) => `set -g ${k} ${quote(v)}`)].join("\n"))
        .join("\n\n");
    return `${HEADER}
# ${mode.type === "dark" ? "Dark" : "Light"} - source this file from ~/.tmux.conf. Leaves the terminal's own colors alone.

${body}

# Optional: heavier pane borders (tmux 3.2+), e.g. single, double, heavy, simple
# set -g pane-border-lines heavy
`;
}

export default definePort({
    id: "tmux",
    name: "tmux",
    category: "terminal",
    description: "Terminal multiplexer: status bar, window list, pane borders, copy mode, messages, popups and menus.",
    homepage: "https://github.com/tmux/tmux",
    tags: ["multiplexer", "tui", "linux", "macos"],
    install: `
Copy \`termicolor-dark.conf\` (or \`-light\`) to \`~/.config/tmux/\` and source it from \`~/.tmux.conf\`
(or \`~/.config/tmux/tmux.conf\`), after any other style settings. No plugin manager needed:

\`\`\`tmux
source-file ~/.config/tmux/termicolor-dark.conf
\`\`\`

Reload with \`tmux source-file ~/.tmux.conf\`. The status line uses plain text only, no Nerd Font.
The session name turns yellow while the prefix key is held.

Only tmux's own UI is themed: the terminal colors inside panes come from your terminal emulator theme.
The copy mode search styles (\`copy-mode-match-style\`, \`copy-mode-current-match-style\`,
\`copy-mode-mark-style\`) need tmux 3.4+. On older versions delete those lines.
`,
    build: (palette) => [
        {path: "termicolor-dark.conf", contents: theme(palette.modes.dark)},
        {path: "termicolor-light.conf", contents: theme(palette.modes.light)},
    ],
});
