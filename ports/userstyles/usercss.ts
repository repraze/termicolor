import type {Palette} from "@repraze/termicolor";
import {REPO_URL} from "@termicolor/build";

import pkg from "../../package.json" with {type: "json"};

/** A CSS custom property and its value. */
export type Variable = [name: string, value: string];

/** One website restyle: its own `.user.css` file in `dist/`. */
export type Site = {
    /** File stem, `<id>.user.css`. */
    id: string;
    name: string;
    description: string;
    /** `@-moz-document` matchers, e.g. `domain("github.com")`. */
    matchers: string[];
    /** The style body inside `@-moz-document`, unindented. */
    body(palette: Palette): string;
};

export function fileName(site: Site): string {
    return `${site.id}.user.css`;
}

/** Where Stylus fetches the style from, and checks for updates. */
export function rawUrl(site: Site): string {
    return `${REPO_URL}/raw/main/ports/userstyles/dist/${fileName(site)}`;
}

export function indent(text: string, depth = 1): string {
    const pad = "    ".repeat(depth);
    return text
        .split("\n")
        .map((line) => (line ? pad + line : line))
        .join("\n");
}

/** `selectors { --name: value; ... }`, one selector per line. */
export function rule(selectors: string[], variables: Variable[]): string {
    return [`${selectors.join(",\n")} {`, ...variables.map(([name, value]) => `    ${name}: ${value};`), "}"].join(
        "\n",
    );
}

/** The full `.user.css`: UserCSS metadata, then the body scoped to the site's domains. */
export function userCss(site: Site, palette: Palette): string {
    return `/* ==UserStyle==
@name Termicolor for ${site.name}
@namespace github.com/repraze/termicolor
@version ${pkg.version}
@description ${site.description}
@author repraze
@license MIT
@homepageURL ${REPO_URL}/tree/main/ports/userstyles
@updateURL ${rawUrl(site)}
@preprocessor default
==/UserStyle== */

/* Generated by termicolor, do not edit. */

@-moz-document ${site.matchers.join(", ")} {
${indent(site.body(palette))}
}
`;
}
