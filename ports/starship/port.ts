import {definePort} from "@termicolor/build";
import type {Mode} from "@termicolor/palette";

function paletteBlock({name, accents: a, roles: r}: Mode): string {
    const entries: [string, string][] = [
        ...Object.entries(a),
        ["text", r.fg],
        ["subtext", r.fgSoft],
        ["surface", r.bgRaised],
        ["base", r.bg],
        // powerline segment text: deepest neutral in dark, white in light (accents are text-safe on it)
        ["crust", name === "dark" ? r.bgSunken : r.bg],
    ];
    return [`[palettes.termicolor_${name}]`, ...entries.map(([k, v]) => `${k} = "${v}"`)].join("\n");
}

