import type {Mode} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

function paletteBlock({name, accents: a, fills, onFill, roles: r}: Mode): string {
    const entries: [string, string][] = [
        // text tier: prompt characters and other colored text
        ...Object.entries(a),
        // fill tier: solid powerline segments, with their paired text color
        ...Object.entries(fills).map(([k, v]): [string, string] => [`fill_${k}`, v]),
        ...Object.entries(onFill).map(([k, v]): [string, string] => [`on_fill_${k}`, v]),
        ["text", r.fg],
        ["subtext", r.fgSoft],
        ["surface", r.bgRaised],
        ["base", r.bg],
        ["crust", r.bgSunken],
    ];
    return [`[palettes.termicolor_${name}]`, ...entries.map(([k, v]) => `${k} = "${v}"`)].join("\n");
}

