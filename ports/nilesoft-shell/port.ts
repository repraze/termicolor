import {type Mode, solid} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

const HEADER = "// Termicolor for Nilesoft Shell - generated by https://github.com/repraze/termicolor - do not edit.";

/** The context menu's colors for one mode. */
function colors({roles: r}: Mode) {
    return {
        // the menu is a popup: raised surface, strong border
        background: r.bgRaised,
        border: r.borderStrong,
        shadow: r.shadow,
        // r.border equals bgRaised in dark, so separators use the strong border
        separator: r.borderStrong,
        text: r.fg,
        textDisabled: r.fgDisabled,
        // highlighted item: accent tint with fg text (DESIGN.md §6)
        select: r.accentTint,
        // a disabled item under the pointer only gets the hover wash
        selectDisabled: solid(r.bgHover, r.bgRaised),
        symbol: r.fgSoft,
        symbolDisabled: r.fgDisabled,
        accent: r.accent,
    };
}

type Colors = ReturnType<typeof colors>;

/**
 * The `theme` block. `v` turns a color key into the value written in the file: a literal for one mode,
 * or an `@if(sys.dark, ...)` expression for the file that follows Windows.
 */
function theme(dark: string, v: (key: keyof Colors) => string): string {
    return `${HEADER}

theme
{
    name = "modern"
    dark = ${dark}
    background
    {
        color = ${v("background")}
        opacity = 100
        effect = 0
    }
    item
    {
        opacity = 100
        text
        {
            normal = ${v("text")}
            select = ${v("text")}
            normal.disabled = ${v("textDisabled")}
            select.disabled = ${v("textDisabled")}
        }
        back
        {
            select = ${v("select")}
            select.disabled = ${v("selectDisabled")}
        }
        border
        {
            select = ${v("select")}
            select.disabled = ${v("selectDisabled")}
        }
    }
    border
    {
        enabled = true
        size = 1
        color = ${v("border")}
        opacity = 100
    }
    shadow
    {
        enabled = true
        color = ${v("shadow")}
        opacity = 100
    }
    separator
    {
        size = 1
        color = ${v("separator")}
    }
    symbol
    {
        normal = ${v("symbol")}
        select = ${v("text")}
        normal.disabled = ${v("symbolDisabled")}
        select.disabled = ${v("symbolDisabled")}
    }
    image
    {
        enabled = true
        color = [${v("text")}, ${v("accent")}, ${v("background")}]
    }
}
`;
}

export default definePort({
    id: "nilesoft-shell",
    name: "Nilesoft Shell",
    category: "system",
    description: "Windows context menu theme: menu surface, highlighted item, border, separators and glyphs.",
    homepage: "https://nilesoft.org",
    tags: ["windows", "context-menu", "explorer"],
    install: `
Open the Shell folder: hold **Shift**, right-click the taskbar, then *Shell → directory*.

1. Copy \`termicolor.nss\` (follows the Windows light/dark setting), or \`termicolor-dark.nss\` /
   \`termicolor-light.nss\` for a fixed mode, into the \`imports\` folder.
2. In \`shell.nss\`, replace the theme import with yours:

   \`\`\`
   import 'imports/termicolor.nss'
   \`\`\`

3. Reload: hold **Shift**, right-click the taskbar and choose *Exit Explorer* (Explorer restarts on its own).
`,
    build: (palette) => {
        const {dark, light} = palette.modes;
        const d = colors(dark);
        const l = colors(light);
        return [
            {path: "termicolor.nss", contents: theme("auto", (k) => `@if(sys.dark, ${d[k]}, ${l[k]})`)},
            {path: "termicolor-dark.nss", contents: theme("true", (k) => d[k])},
            {path: "termicolor-light.nss", contents: theme("false", (k) => l[k])},
        ];
    },
});
