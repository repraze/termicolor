import {type Hex, type Mode, solid} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

/**
 * `color.ini` keys, in spicetify's own order (`BaseColorOrder` in spicetify-cli). Each becomes
 * `--spice-<key>` and `--spice-rgb-<key>`. Values are 6-digit hex without `#`: spicetify drops any alpha.
 */
function colors({roles: r, tints, neutrals}: Mode): [string, Hex][] {
    return [
        ["text", r.fg],
        ["subtext", r.fgSoft],
        ["main", r.bg],
        ["main-elevated", r.bgRaised],
        // hover washes over the surface below them
        ["highlight", solid(r.bgHover, r.bg)],
        ["highlight-elevated", solid(r.bgHover, r.bgRaised)],
        ["sidebar", r.bgSunken],
        ["player", r.bgSunken],
        // card background on hover; resting cards use `player`
        ["card", r.bgRaised],
        // spotify applies its own alpha: rgba(var(--spice-rgb-shadow), .3)
        ["shadow", neutrals[1000]],
        // a text color: spotify draws it at low alpha for the selected row, scrollbars and captions
        ["selected-row", r.fg],
        // play button fill, and text/icon color for the playing track, liked heart, active toggles
        ["button", r.accent],
        ["button-active", r.accentBright],
        // seekbar and volume track
        ["button-disabled", r.borderStrong],
        // active chip/tab in the header: fg text on the accent tint
        ["tab-active", r.accentTint],
        // toasts carry `text` on them, so opaque tints rather than fills
        ["notification", tints.blue],
        ["notification-error", tints.red],
        ["misc", r.fgMuted],
        // extra key for user.css: opaque text selection behind fg text
        ["selection", solid(r.selection, r.bg)],
    ];
}

function section(name: string, mode: Mode): string {
    const entries = colors(mode);
    const width = Math.max(...entries.map(([key]) => key.length));
    return [`[${name}]`, ...entries.map(([key, hex]) => `${key.padEnd(width)} = ${hex.slice(1, 7)}`)].join("\n");
}

const USER_CSS = `/* Termicolor for Spicetify - colors live in color.ini. Generated by termicolor, do not edit. */

::selection {
    background-color: var(--spice-selection);
    color: var(--spice-text);
}
`;

export default definePort({
    id: "spicetify",
    name: "Spotify (Spicetify)",
    category: "app",
    description: "Spotify theme",
    homepage: "https://spicetify.app/",
    tags: ["spotify", "music", "spicetify"],
    install: `
Needs [Spicetify](https://spicetify.app/). Copy the \`Termicolor\` folder into Spicetify's \`Themes\` folder, so you
end up with \`Themes/Termicolor/color.ini\` and \`user.css\`:

| OS            | Path                            |
| ------------- | ------------------------------- |
| Linux / macOS | \`~/.config/spicetify/Themes/\` |
| Windows       | \`%APPDATA%\\spicetify\\Themes\\\` |

(\`spicetify path userdata\` prints the folder that holds \`Themes\`.) Then pick the theme and a color scheme,
\`dark\` or \`light\`, and apply:

\`\`\`sh
spicetify config current_theme Termicolor color_scheme dark
spicetify apply
\`\`\`
`,
    build: (palette) => [
        {
            path: "Termicolor/color.ini",
            contents: `; Termicolor for Spicetify - generated by https://github.com/repraze/termicolor\n\n${section("dark", palette.modes.dark)}\n\n${section("light", palette.modes.light)}\n`,
        },
        {path: "Termicolor/user.css", contents: USER_CSS},
    ],
});
