import {definePort} from "@termicolor/build";
import type {Ansi, Mode} from "@termicolor/palette";

type Value = string | string[] | {[key: string]: Value};
type Table = {[key: string]: Value};

const ANSI_NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"] as const;
const BRIGHT_NAMES = ANSI_NAMES.map((n) => `bright${n.charAt(0).toUpperCase()}${n.slice(1)}` as keyof Ansi);

const title = (mode: Mode) => `Termicolor ${mode.type === "dark" ? "Dark" : "Light"}`;

/** The `colors` table, shared by the TOML scheme files and the Lua module. */
function colors(mode: Mode): Table {
    const {roles: r, accents: a, fills, onFill, ansi} = mode;
    // Opaque everywhere (the `*Solid` roles) so the result doesn't depend on wezterm's blending.
    const tab = (bg: string, fg: string) => ({bg_color: bg, fg_color: fg});
    return {
        foreground: r.fg,
        background: r.bg,
        cursor_bg: r.cursor,
        cursor_fg: r.onAccent,
        cursor_border: r.cursor,
        compose_cursor: a.orange,
        selection_bg: r.selectionSolid,
        selection_fg: r.fg,
        scrollbar_thumb: r.borderStrong,
        split: r.borderStrong,
        visual_bell: r.bgRaised,
        ansi: ANSI_NAMES.map((n) => ansi[n]),
        brights: BRIGHT_NAMES.map((n) => ansi[n]),
        copy_mode_active_highlight_bg: r.matchActive,
        copy_mode_active_highlight_fg: r.onMatchActive,
        copy_mode_inactive_highlight_bg: r.findMatchSolid,
        copy_mode_inactive_highlight_fg: r.fg,
        quick_select_label_bg: fills.yellow,
        quick_select_label_fg: onFill.yellow,
        quick_select_match_bg: r.findMatchSolid,
        quick_select_match_fg: r.fg,
        tab_bar: {
            // retro tab bar only; the fancy one is drawn on window_frame
            background: r.tabInactive,
            inactive_tab_edge: r.border,
            active_tab: tab(r.tabActive, r.tabActiveFg),
            inactive_tab: tab(r.tabInactive, r.tabInactiveFg),
            inactive_tab_hover: tab(r.bgRaised, r.fg),
            new_tab: tab(r.tabInactive, r.tabInactiveFg),
            new_tab_hover: tab(r.accent, r.onAccent),
        },
    };
}

/** Fancy tab bar / titlebar colors. Not part of a color scheme, so only the Lua module sets them. */
function windowFrame({roles: r}: Mode): Table {
    return {
        active_titlebar_bg: r.titlebar,
        inactive_titlebar_bg: r.titlebar,
        active_titlebar_fg: r.fg,
        inactive_titlebar_fg: r.fgSoft,
        active_titlebar_border_bottom: r.border,
        inactive_titlebar_border_bottom: r.border,
        button_fg: r.fgSoft,
        button_bg: r.titlebar,
        button_hover_fg: r.fg,
        button_hover_bg: r.bgRaised,
    };
}

const quote = (s: string) => JSON.stringify(s);

function toml(mode: Mode): string {
    const scalars = (table: Table) =>
        Object.entries(table)
            .filter(([, v]) => !isTable(v))
            .map(([k, v]) => `${k} = ${Array.isArray(v) ? `[${v.map(quote).join(", ")}]` : quote(v as string)}`);
    const sections = (name: string, table: Table): string[] => [
        [`[${name}]`, ...scalars(table)].join("\n"),
        ...Object.entries(table)
            .filter((e): e is [string, Table] => isTable(e[1]))
            .flatMap(([k, v]) => sections(`${name}.${k}`, v)),
    ];
    return `# ${title(mode)} - generated by https://github.com/repraze/termicolor

${[
    ...sections("metadata", {
        name: title(mode),
        author: "repraze",
        origin_url: "https://github.com/repraze/termicolor",
    }),
    ...sections("colors", colors(mode)),
].join("\n\n")}
`;
}

function isTable(v: Value): v is Table {
    return typeof v === "object" && !Array.isArray(v);
}

function lua(v: Value, indent: string): string {
    if (typeof v === "string") {
        return quote(v);
    }
    const inner = `${indent}    `;
    if (Array.isArray(v)) {
        return `{${v.map(quote).join(", ")}}`;
    }
    return `{\n${Object.entries(v)
        .map(([k, x]) => `${inner}${/^[a-z_]\w*$/i.test(k) ? k : `[${quote(k)}]`} = ${lua(x, inner)},`)
        .join("\n")}\n${indent}}`;
}

function module(modes: Mode[]): string {
    const schemes: Table = Object.fromEntries(modes.map((m) => [title(m), colors(m)]));
    const frames: Table = Object.fromEntries(modes.map((m) => [m.type, windowFrame(m)]));
    return `-- Termicolor for WezTerm - generated by https://github.com/repraze/termicolor
--
-- local termicolor = require("termicolor")
-- termicolor.apply_to_config(config)            -- follows the OS light/dark setting
-- termicolor.apply_to_config(config, "dark")    -- or pin "dark" / "light"

local wezterm = require("wezterm")

local M = {}

M.color_schemes = ${lua(schemes, "")}

M.window_frames = ${lua(frames, "")}

M.names = {${modes.map((m) => `${m.type} = ${quote(title(m))}`).join(", ")}}

--- "dark" or "light" from the OS appearance (the mux server has no GUI, so it defaults to dark).
function M.appearance()
    if wezterm.gui and not wezterm.gui.get_appearance():find("Dark") then
        return "light"
    end
    return "dark"
end

function M.apply_to_config(config, mode)
    mode = mode or M.appearance()
    config.color_schemes = config.color_schemes or {}
    for name, scheme in pairs(M.color_schemes) do
        config.color_schemes[name] = scheme
    end
    config.color_scheme = M.names[mode]
    config.window_frame = config.window_frame or {}
    for key, value in pairs(M.window_frames[mode]) do
        config.window_frame[key] = value
    end
end

return M
`;
}

export default definePort({
    id: "wezterm",
    name: "WezTerm",
    category: "terminal",
    description:
        "Dark and light WezTerm color schemes (TOML) plus a Lua module that also themes the fancy tab bar and follows the OS appearance.",
    homepage: "https://wezterm.org",
    tags: ["lua", "gpu", "multiplexer", "ansi"],
    install: `
**Lua module (recommended):** copy \`termicolor.lua\` into \`~/.config/wezterm/\` and add to \`wezterm.lua\`:

\`\`\`lua
local termicolor = require("termicolor")
termicolor.apply_to_config(config) -- or termicolor.apply_to_config(config, "light")
\`\`\`

It registers both schemes, picks one from the OS light/dark setting and colors the fancy tab bar
(\`window_frame\`). WezTerm reloads the config when the appearance changes.

**Scheme files only:** copy \`colors/termicolor-dark.toml\` and \`colors/termicolor-light.toml\` into
\`~/.config/wezterm/colors/\` (or a \`colors\` folder next to \`wezterm.exe\` on Windows) and set:

\`\`\`lua
config.color_scheme = "Termicolor Dark"
\`\`\`
`,
    build: (palette) => {
        const modes = [palette.modes.dark, palette.modes.light];
        return [
            {path: "termicolor.lua", contents: module(modes)},
            ...modes.map((m) => ({path: `colors/termicolor-${m.type}.toml`, contents: toml(m)})),
        ];
    },
});
