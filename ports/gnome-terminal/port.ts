import {definePort} from "@termicolor/build";
import type {Mode} from "@termicolor/palette";

/** Fixed profile ids, so re-running the installer updates the same profiles. */
const UUIDS = {dark: "46edc057-d8e6-4aa1-a6a2-3b83272ead24", light: "5c7f0537-5c7f-4f86-8e09-fadd0a973257"};

const ANSI_ORDER = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "brightBlack",
    "brightRed",
    "brightGreen",
    "brightYellow",
    "brightBlue",
    "brightMagenta",
    "brightCyan",
    "brightWhite",
] as const;

const str = (value: string) => `'${value}'`;

const title = (mode: Mode) => `Termicolor ${mode.type === "dark" ? "Dark" : "Light"}`;

/** `org.gnome.Terminal.Legacy.Profile` keys, as GVariant text (shared by dconf files and gsettings). */
function keys(mode: Mode): [string, string][] {
    const {roles: r, ansi} = mode;
    return [
        ["visible-name", str(title(mode))],
        ["use-theme-colors", "false"],
        ["foreground-color", str(r.fg)],
        ["background-color", str(r.bg)],
        ["palette", `[${ANSI_ORDER.map((name) => str(ansi[name])).join(", ")}]`],
        ["bold-color-same-as-fg", "true"],
        ["bold-color", str(r.fg)],
        ["cursor-colors-set", "true"],
        ["cursor-background-color", str(r.cursor)],
        ["cursor-foreground-color", str(r.onAccent)],
        // GNOME Terminal paints the selection opaque: use the solid selection.
        ["highlight-colors-set", "true"],
        ["highlight-background-color", str(r.selectionSolid)],
        ["highlight-foreground-color", str(r.fg)],
    ];
}

function dconf(mode: Mode): string {
    return `# ${title(mode)} for GNOME Terminal - generated by https://github.com/repraze/termicolor
# dconf load /org/gnome/terminal/legacy/profiles:/:${UUIDS[mode.name]}/ < termicolor-${mode.name}.dconf
[/]
${keys(mode)
    .map(([k, v]) => `${k}=${v}`)
    .join("\n")}
`;
}

function installer(modes: Mode[]): string {
    const profiles = modes
        .map(
            (mode) => `install_${mode.name}() {
    local path
    path=$(add_profile ${UUIDS[mode.name]})
${keys(mode)
    .map(([k, v]) => `    gsettings set "$path" ${k} "${v}"`)
    .join("\n")}
    echo "Installed ${title(mode)}"
}`,
        )
        .join("\n\n");
    return `#!/usr/bin/env bash
# Termicolor for GNOME Terminal - generated by https://github.com/repraze/termicolor
#
# Usage: ./install.sh [dark|light|both] [--default]
#   --default also makes the profile GNOME Terminal's default (the first one, with "both").
set -euo pipefail

LIST=org.gnome.Terminal.ProfilesList
PROFILE=org.gnome.Terminal.Legacy.Profile

# Registers a profile id in the profile list and prints its gsettings schema:path.
add_profile() {
    local uuid=$1 list
    list=$(gsettings get "$LIST" list)
    if [[ $list != *"'$uuid'"* ]]; then
        if [[ $list == "@as []" || $list == "[]" ]]; then
            list="['$uuid']"
        else
            list="\${list%]}, '$uuid']"
        fi
        gsettings set "$LIST" list "$list"
    fi
    echo "$PROFILE:/org/gnome/terminal/legacy/profiles:/:$uuid/"
}

${profiles}

which=\${1:-both}
default=\${2:-}
if [[ $which == "--default" ]]; then
    which=both
    default=--default
fi

case $which in
    dark) install_dark; uuid=${UUIDS.dark} ;;
    light) install_light; uuid=${UUIDS.light} ;;
    both) install_dark; install_light; uuid=${UUIDS.dark} ;;
    *) echo "usage: $0 [dark|light|both] [--default]" >&2; exit 1 ;;
esac

if [[ $default == "--default" ]]; then
    gsettings set "$LIST" default "$uuid"
    echo "Set as default profile"
fi
`;
}

export default definePort({
    id: "gnome-terminal",
    name: "GNOME Terminal",
    category: "terminal",
    description: "Dark and light profiles for GNOME Terminal, installed through gsettings or dconf.",
    homepage: "https://gitlab.gnome.org/GNOME/gnome-terminal",
    tags: ["linux", "gnome", "dconf", "gsettings", "ansi"],
    install: `
**Script:** run \`install.sh\` to add *Termicolor Dark* and *Termicolor Light* profiles:

\`\`\`sh
bash install.sh                 # both profiles
bash install.sh dark --default   # one profile, made the default
\`\`\`

Re-running it updates the same profiles in place. Pick a profile in *Preferences* or from the
new-tab menu.

**dconf:** load a single profile by hand, then add its id to the profile list
(\`org.gnome.Terminal.ProfilesList list\`) so it shows up:

\`\`\`sh
dconf load /org/gnome/terminal/legacy/profiles:/:${UUIDS.dark}/ < termicolor-dark.dconf
\`\`\`

The light profile's id is \`${UUIDS.light}\`.
`,
    build: (palette) => {
        const {dark, light} = palette.modes;
        return [
            {path: "install.sh", contents: installer([dark, light])},
            {path: "termicolor-dark.dconf", contents: dconf(dark)},
            {path: "termicolor-light.dconf", contents: dconf(light)},
        ];
    },
});
