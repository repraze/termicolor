/** A full VS Code color theme. Also valid as a TextMate theme for shiki / Monaco. */
export function vscodeTheme(mode: Mode) {
    return {
        $schema: "vscode://schemas/color-theme",
        name: `Termicolor ${mode.type === "dark" ? "Dark" : "Light"}`,
        type: mode.type,
        semanticHighlighting: true,
        colors: workbench(mode),
        semanticTokenColors: semanticTokenColors(mode),
        tokenColors: tokenColors(mode),
    };
}

export default definePort({
    id: "vscode",
    name: "Visual Studio Code",
    category: "editor",
    description: "Dark and light color themes for VS Code and VSCodium, matching repraze.com code blocks.",
    homepage: "https://code.visualstudio.com",
    tags: ["vscodium", "cursor", "editor", "monaco"],
    install: `
Not on the Marketplace yet. Package and install the extension folder:

\`\`\`sh
cd ports/vscode/dist
npx @vscode/vsce package -o termicolor.vsix
code --install-extension termicolor.vsix
\`\`\`

Then pick **Termicolor Dark** or **Termicolor Light** in *Preferences: Color Theme*.
`,
    build: (palette) => [
        {
            path: "package.json",
            contents: json({
                name: "termicolor",
                displayName: "Termicolor",
                description: "High contrast, bright, techy color theme",
                version: pkg.version,
                publisher: "repraze",
                license: "MIT",
                repository: {type: "git", url: "https://github.com/repraze/termicolor"},
                engines: {vscode: "^1.80.0"},
                categories: ["Themes"],
                contributes: {
                    themes: [
                        {label: "Termicolor Dark", uiTheme: "vs-dark", path: "./themes/termicolor-dark.json"},
                        {label: "Termicolor Light", uiTheme: "vs", path: "./themes/termicolor-light.json"},
                    ],
                },
            }),
        },
        {path: "README.md", contents: "# Termicolor\n\nHigh contrast, bright, techy color theme.\n"},
        {path: "LICENSE", contents: "MIT License\n\nCopyright (c) Thomas Dubosc\n"},
        {path: "themes/termicolor-dark.json", contents: json(vscodeTheme(palette.modes.dark))},
        {path: "themes/termicolor-light.json", contents: json(vscodeTheme(palette.modes.light))},
    ],
});
