import {type Hex, type Mode, solid, tint} from "@repraze/termicolor";

/** An `nvim_set_hl` spec. Unset colors stay NONE, so groups inherit from `Normal` / the window. */
export type Spec = {
    fg?: Hex;
    bg?: Hex;
    sp?: Hex;
    bold?: true;
    italic?: true;
    underline?: true;
    undercurl?: true;
    strikethrough?: true;
    link?: string;
};

export type Section = {title: string; groups: [string, Spec][]};

/** LSP completion item kinds, shared by nvim-cmp (`CmpItemKind*`) and blink.cmp (`BlinkCmpKind*`). */
function completionKinds({roles: r, syntax: s, files}: Mode): Record<string, Hex> {
    return {
        Text: r.fg,
        Method: s.function,
        Function: s.function,
        Constructor: s.type,
        Field: s.property,
        Variable: s.variable,
        Class: s.type,
        Interface: s.type,
        Module: s.type,
        Property: s.property,
        Unit: s.number,
        Value: s.number,
        Enum: s.type,
        Keyword: s.keyword,
        Snippet: s.builtin,
        Color: s.string,
        File: r.fg,
        Reference: s.variable,
        Folder: files.directory,
        EnumMember: s.constant,
        Constant: s.constant,
        Struct: s.type,
        Event: s.function,
        Operator: s.operator,
        TypeParameter: s.type,
    };
}

