import {type Ansi, type Mode} from "@repraze/termicolor";
import {definePort} from "@termicolor/build";

import {highlights, type Spec} from "./highlights.ts";

const HEADER = "-- Termicolor for Neovim - generated by https://github.com/repraze/termicolor";

const ANSI_ORDER: (keyof Ansi)[] = [
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "brightBlack",
    "brightRed",
    "brightGreen",
    "brightYellow",
    "brightBlue",
    "brightMagenta",
    "brightCyan",
    "brightWhite",
];

const SPEC_KEYS = ["link", "fg", "bg", "sp", "bold", "italic", "underline", "undercurl", "strikethrough"] as const;

/** `{fg = "#...", bold = true}` */
function luaSpec(spec: Spec): string {
    const fields = SPEC_KEYS.filter((key) => spec[key] !== undefined).map((key) => {
        const value = spec[key];
        return `${key} = ${value === true ? "true" : JSON.stringify(value)}`;
    });
    return `{${fields.join(", ")}}`;
}

function colorscheme(mode: Mode): string {
    const name = `termicolor-${mode.type}`;
    const sections = highlights(mode).map(({title, groups}) =>
        [`-- ${title}`, ...groups.map(([group, spec]) => `hl(0, ${JSON.stringify(group)}, ${luaSpec(spec)})`)].join(
            "\n",
        ),
    );
    const terminal = ANSI_ORDER.map((key, i) => `vim.g.terminal_color_${i} = "${mode.ansi[key]}"`).join("\n");
    return `${HEADER}
-- Termicolor ${mode.type === "dark" ? "Dark" : "Light"}: high contrast, bright, techy colors. Do not edit.

vim.cmd("highlight clear")
if vim.fn.exists("syntax_on") == 1 then
    vim.cmd("syntax reset")
end
vim.o.background = "${mode.type}"
vim.o.termguicolors = true
vim.g.colors_name = "${name}"

local hl = vim.api.nvim_set_hl

${sections.join("\n\n")}

-- Terminal
${terminal}
`;
}

/** `:colorscheme termicolor`: the dark or light scheme, following 'background'. */
const AUTO = `${HEADER}
-- Termicolor: Dark or Light, following 'background'. Do not edit.

local mode = vim.o.background == "light" and "light" or "dark"
vim.cmd("runtime colors/termicolor-" .. mode .. ".lua")
-- keep the switching name, so \`:set background=light\` reloads this file
vim.g.colors_name = "termicolor"
`;

export default definePort({
    id: "nvim",
    name: "Neovim",
    category: "editor",
    description:
        "Lua colorschemes for Neovim 0.9+: editor UI, diagnostics, treesitter, LSP semantic tokens, terminal " +
        "colors and popular plugins (gitsigns, telescope, nvim-cmp, blink.cmp, which-key, neo-tree, ...).",
    homepage: "https://neovim.io",
    tags: ["vim", "lua", "treesitter"],
    install: `
The \`dist/\` folder is a plugin (it has a \`colors/\` directory). Neovim only (Lua); plain Vim isn't supported.

**lazy.nvim**, from a clone of this repo:

\`\`\`lua
{
    dir = "~/src/termicolor/ports/nvim/dist",
    name = "termicolor",
    lazy = false,
    priority = 1000,
    config = function()
        vim.cmd.colorscheme("termicolor")
    end,
}
\`\`\`

**Manual:** copy the \`colors/*.lua\` files into \`~/.config/nvim/colors/\`
(Windows: \`~/AppData/Local/nvim/colors/\`), then:

\`\`\`lua
vim.cmd.colorscheme("termicolor") -- follows 'background'; or "termicolor-dark" / "termicolor-light"
\`\`\`

**Rainbow brackets:** rainbow-delimiters.nvim uses the theme's colors as is. For the exact six-color cycle:

\`\`\`lua
vim.g.rainbow_delimiters = {
    highlight = {
        "TermicolorBracket1", "TermicolorBracket2", "TermicolorBracket3",
        "TermicolorBracket4", "TermicolorBracket5", "TermicolorBracket6",
    },
}
\`\`\`
`,
    build: (palette) => [
        {path: "colors/termicolor.lua", contents: AUTO},
        {path: "colors/termicolor-dark.lua", contents: colorscheme(palette.modes.dark)},
        {path: "colors/termicolor-light.lua", contents: colorscheme(palette.modes.light)},
    ],
});
