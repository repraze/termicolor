import {catalogTable} from "./catalog.ts";

export const TABLE_START = "<!-- catalog:start (generated by `npm run catalog -w @termicolor/wallpapers`) -->";
export const TABLE_END = "<!-- catalog:end -->";

/** CATALOG.md with the text between the markers replaced by the generated table. */
export function replaceCatalogTable(doc: string): string {
    const start = doc.indexOf(TABLE_START);
    const end = doc.indexOf(TABLE_END);
    if (start < 0 || end < start) {
        throw new Error("CATALOG.md is missing the catalog:start / catalog:end markers");
    }
    return `${doc.slice(0, start + TABLE_START.length)}\n\n${catalogTable()}\n\n${doc.slice(end)}`;
}
